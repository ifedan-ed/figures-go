// Command refgen writes the reference tables the clinical charts draw
// from (refdata.go): the WHO and CDC growth references' LMS parameters,
// and the AAP 2017 blood pressure percentiles for children aged 1 to 12.
//
// It downloads each table from its publisher (or reads the same files from
// -dir) and copies the numbers as published, digit for digit; nothing is
// fitted or rounded here. Run it from internal/chart:
//
//	go generate ./internal/chart          (downloads)
//	go run ./refgen -dir /path/to/files   (files already fetched)
package main

import (
	"bufio"
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"strings"
	"time"
)

// A growth table: one sex's LMS rows for one measure.
type growthSource struct {
	key  string // the Go name's stem: whoWeight
	sex  string // "male" or "female"
	url  string
	cdc  bool // CDC files hold both sexes, Sex 1 = male, 2 = female
	note string
}

const (
	cdcBase = "https://www.cdc.gov/growthcharts/data/zscore/"
	whoBase = "https://ftp.cdc.gov/pub/Health_Statistics/NCHS/growthcharts/"
	bpBase  = "https://raw.githubusercontent.com/dewittpe/pedbp/main/data-raw/"
)

var growth = []growthSource{
	{"whoWeight", "male", whoBase + "WHO-Boys-Weight-for-age-Percentiles.csv", false, ""},
	{"whoWeight", "female", whoBase + "WHO-Girls-Weight-for-age%20Percentiles.csv", false, ""},
	{"whoLength", "male", whoBase + "WHO-Boys-Length-for-age-Percentiles.csv", false, ""},
	{"whoLength", "female", whoBase + "WHO-Girls-Length-for-age-Percentiles.csv", false, ""},
	{"whoHead", "male", whoBase + "WHO-Boys-Head-Circumference-for-age-Percentiles.csv", false, ""},
	{"whoHead", "female", whoBase + "WHO-Girls-Head-Circumference-for-age-Percentiles.csv", false, ""},
	{"cdcWeight", "male", cdcBase + "wtage.csv", true, ""},
	{"cdcWeight", "female", cdcBase + "wtage.csv", true, ""},
	{"cdcStature", "male", cdcBase + "statage.csv", true, ""},
	{"cdcStature", "female", cdcBase + "statage.csv", true, ""},
	{"cdcBMI", "male", cdcBase + "bmiagerev.csv", true, ""},
	{"cdcBMI", "female", cdcBase + "bmiagerev.csv", true, ""},
}

var bpFiles = map[string]string{
	"male":   bpBase + "flynn2017_bp_boys.dat",
	"female": bpBase + "flynn2017_bp_girls.dat",
}

func main() {
	out := flag.String("out", "refdata.go", "file to write")
	dir := flag.String("dir", "", "read the files from here (by their names in the URLs) instead of downloading")
	date := flag.String("date", time.Now().UTC().Format("2006-01-02"), "the date the files were fetched, for the header")
	flag.Parse()
	files := map[string][]byte{}
	get := func(url string) []byte {
		if b, ok := files[url]; ok {
			return b
		}
		var b []byte
		var err error
		if *dir != "" {
			name := strings.ReplaceAll(path.Base(url), "%20", "-")
			b, err = os.ReadFile(filepath.Join(*dir, name))
			if os.IsNotExist(err) {
				b, err = os.ReadFile(filepath.Join(*dir, path.Base(url)))
			}
		} else {
			b, err = fetch(url)
		}
		if err != nil {
			log.Fatalf("%s: %v", url, err)
		}
		b = bytes.TrimPrefix(b, []byte("\xef\xbb\xbf"))
		files[url] = b
		return b
	}

	var w bytes.Buffer
	fmt.Fprintf(&w, "// Code generated by refgen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&w, "// The numbers below are copied as published, fetched on %s from:\n//\n", *date)
	seen := map[string]bool{}
	for _, g := range growth {
		if !seen[g.url] {
			fmt.Fprintf(&w, "//   %s\n", g.url)
			seen[g.url] = true
		}
	}
	fmt.Fprintf(&w, "//   %s\n//   %s\n", bpFiles["male"], bpFiles["female"])
	fmt.Fprintf(&w, `//
// The WHO tables are the WHO Child Growth Standards (2006) for 0 to 24
// months as the CDC republishes them; the CDC tables are the CDC 2000
// growth charts for 2 to 20 years. Both are public-domain US government
// works. The blood pressure tables are Tables 4 and 5 of Flynn JT et al.,
// Clinical Practice Guideline for Screening and Management of High Blood
// Pressure in Children and Adolescents, Pediatrics 2017;140(3):e20171904,
// as transcribed in the pedbp R package's data-raw (Peter DeWitt et al.);
// they are measurements, reproduced here with attribution, and are checked
// against the guideline's Table 3 in the tests.

package chart

`)
	keys := []string{}
	byKey := map[string][2][]string{}
	for _, g := range growth {
		rows := lmsRows(get(g.url), g)
		v := byKey[g.key]
		if g.sex == "female" {
			v[0] = rows
		} else {
			v[1] = rows
		}
		if _, ok := byKey[g.key]; !ok {
			keys = append(keys, g.key)
		}
		byKey[g.key] = v
	}
	for _, k := range keys {
		v := byKey[k]
		fmt.Fprintf(&w, "// %s is [female, male] rows of {age in months, L, M, S}.\nvar %s = [2][]lms{\n", k, k)
		for _, rows := range v {
			w.WriteString("{\n")
			for _, r := range rows {
				w.WriteString(r + "\n")
			}
			w.WriteString("},\n")
		}
		w.WriteString("}\n\n")
	}
	w.WriteString("// flynn2017 is [female, male][age 1 to 12][50th, 90th, 95th BP percentile][height\n// percentile 5, 10, 25, 50, 75, 90, 95] as {systolic, diastolic} in mmHg.\nvar flynn2017 = [2][12][3][7][2]float64{\n")
	for _, sex := range []string{"female", "male"} {
		w.WriteString(bpTable(get(bpFiles[sex])))
	}
	w.WriteString("}\n")
	src, err := format.Source(w.Bytes())
	if err != nil {
		log.Fatalf("formatting: %v\n%s", err, w.String())
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func fetch(url string) ([]byte, error) {
	c := &http.Client{Timeout: 60 * time.Second}
	resp, err := c.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return nil, fmt.Errorf("HTTP %d", resp.StatusCode)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 4<<20))
}

// lmsRows are one sex's rows as Go literals: {age, L, M, S}.
func lmsRows(b []byte, g growthSource) []string {
	r := csv.NewReader(bytes.NewReader(b))
	r.FieldsPerRecord = -1
	recs, err := r.ReadAll()
	if err != nil {
		log.Fatalf("%s: %v", g.url, err)
	}
	head := recs[0]
	col := func(name string) int {
		for i, h := range head {
			if strings.EqualFold(strings.TrimSpace(h), name) {
				return i
			}
		}
		log.Fatalf("%s: no column %s in %v", g.url, name, head)
		return -1
	}
	ageCol := "Month"
	if g.cdc {
		ageCol = "Agemos"
	}
	ai, li, mi, si := col(ageCol), col("L"), col("M"), col("S")
	sexCol := -1
	if g.cdc {
		sexCol = col("Sex")
	}
	var out []string
	for _, rec := range recs[1:] {
		if len(rec) <= si || strings.TrimSpace(rec[ai]) == "" {
			continue
		}
		if sexCol >= 0 {
			want := "1"
			if g.sex == "female" {
				want = "2"
			}
			if strings.TrimSpace(rec[sexCol]) != want {
				continue
			}
		}
		out = append(out, fmt.Sprintf("{%s, %s, %s, %s},", num(rec[ai]), num(rec[li]), num(rec[mi]), num(rec[si])))
	}
	if len(out) < 20 {
		log.Fatalf("%s: only %d rows for %s", g.url, len(out), g.sex)
	}
	return out
}

// num checks a field is a plain number and returns it as written.
func num(s string) string {
	s = strings.TrimSpace(s)
	var f float64
	if _, err := fmt.Sscanf(s, "%g", &f); err != nil {
		log.Fatalf("not a number: %q", s)
	}
	return s
}

// bpTable is one sex's ages 1 to 12 as a Go literal. Each line of the file
// is: age, BP percentile, seven systolic values, seven diastolic values.
func bpTable(b []byte) string {
	var rows [13][3][7][2]string
	found := 0
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) != 16 || f[0] == "age" {
			continue
		}
		var age int
		fmt.Sscanf(f[0], "%d", &age)
		if age < 1 || age > 12 {
			continue
		}
		pi := map[string]int{"50": 0, "90": 1, "95": 2}[f[1]]
		if f[1] != "50" && f[1] != "90" && f[1] != "95" {
			log.Fatalf("unexpected BP percentile %q", f[1])
		}
		for h := 0; h < 7; h++ {
			rows[age][pi][h] = [2]string{num(f[2+h]), num(f[9+h])}
		}
		found++
	}
	if found != 36 {
		log.Fatalf("blood pressure table: %d rows for ages 1 to 12, want 36", found)
	}
	var w strings.Builder
	w.WriteString("{\n")
	for age := 1; age <= 12; age++ {
		fmt.Fprintf(&w, "{ // %d years\n", age)
		for pi := 0; pi < 3; pi++ {
			w.WriteString("{")
			for h := 0; h < 7; h++ {
				fmt.Fprintf(&w, "{%s, %s}, ", rows[age][pi][h][0], rows[age][pi][h][1])
			}
			w.WriteString("},\n")
		}
		w.WriteString("},\n")
	}
	w.WriteString("},\n")
	return w.String()
}
